def _f(v: float, nd: int = 3) -> str:
    """Fixed number of significant digits, without exponent for common ranges."""
    if v == 0 or not math.isfinite(v):
        return f"{v:g}"
    mag = math.floor(math.log10(abs(v)))
    decimals = max(nd - 1 - mag, 0)
    return f"{v:.{decimals}f}"


def _pct(v: float, nd: int = 2) -> str:
    return f"{_f(100.0 * v, nd)} %"


def _ms(v: float) -> str:
    return f"{_f(1e3 * v, 3)} ms"


