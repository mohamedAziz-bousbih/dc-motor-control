def replace_block(text: str, content: str, begin: str = README_BEGIN, end: str = README_END) -> str:
    """Replace whatever lies between the markers. The blank line before the
    closing comment keeps a Markdown table from running into it."""
    i, j = text.index(begin) + len(begin), text.index(end)
    return text[:i] + "\n" + content + "\n" + text[j:]


def firmware_header(out: PipelineOutput, drive: DriveParams = DriveParams()) -> str:
    """C header with every number the firmware takes from the design."""
    cfg = out.designs.servo
    sp, pos, ssc = cfg.speed, cfg.pos, cfg.ssc

    def f(v: float) -> str:
        return f"{float(v):.9e}f"

    def d(name: str, value: str, comment: str = "") -> str:
        line = f"#define {name:<22} {value}"
        return f"{line:<46} /* {comment} */" if comment else line

    lines = [
        "/* Generated by scripts/run_pipeline.py from the identified model - do not edit. */",
        "#ifndef CONTROLLER_PARAMS_H",
        "#define CONTROLLER_PARAMS_H",
        "",
        d("CTRL_TS_S", f(cfg.ts), "sample time [s]"),
        d("CTRL_V_SUPPLY", f(drive.v_supply), "H-bridge supply = output limit [V]"),
        d("CTRL_COUNTS_PER_REV", str(drive.counts_per_rev), "x4 counts per output revolution"),
        d("CTRL_RAD_PER_COUNT", f(cfg.rad_per_count), "[rad]"),
        "",
        "/* speed PI: Bode design, anti-windup by back-calculation */",
        d("SPEED_KP", f(sp.kp), "[V s/rad]"),
        d("SPEED_KI", f(sp.ki), "[V/rad]"),
        d("SPEED_KD", f(sp.kd), "[V s^2/rad]"),
        d("SPEED_TF", f(sp.tf), "derivative filter [s]"),
        d("SPEED_B", f(sp.b), "setpoint weight of P"),
        d("SPEED_C", f(sp.c), "setpoint weight of D"),
        d("SPEED_TT", f(sp.tt), "tracking time [s]"),
        d("SPEED_LPF_TAU", f(cfg.speed_lpf_tau), "speed estimate low-pass [s]"),
        d("SPEED_SLEW", f(cfg.speed_slew), "setpoint rate limit [rad/s^2], 0 = off"),
        "",
        "/* position PD: pole compensation + dominant pole pair */",
        d("POS_KP", f(pos.kp), "[V/rad]"),
        d("POS_KI", f(pos.ki), "[V/(rad s)]"),
        d("POS_KD", f(pos.kd), "[V s/rad]"),
        d("POS_TF", f(pos.tf), "derivative filter [s]"),
        d("POS_B", f(pos.b), "setpoint weight of P"),
        d("POS_C", f(pos.c), "setpoint weight of D"),
        d("POS_TT", f(pos.tt), "tracking time [s]"),
        d("POS_SLEW", f(cfg.pos_slew), "setpoint rate limit [rad/s], 0 = off"),
        "",
        "/* state feedback + observer, design model x = [theta, omega] */",
        d("SSC_PHI00", f(ssc.phi[0, 0])),
        d("SSC_PHI01", f(ssc.phi[0, 1])),
        d("SSC_PHI10", f(ssc.phi[1, 0])),
        d("SSC_PHI11", f(ssc.phi[1, 1])),
        d("SSC_GAMMA0", f(ssc.gamma[0])),
        d("SSC_GAMMA1", f(ssc.gamma[1])),
        d("SSC_L0", f(ssc.l[0])),
        d("SSC_L1", f(ssc.l[1])),
        d("SSC_K0", f(ssc.k[0]), "[V/rad]"),
        d("SSC_K1", f(ssc.k[1]), "[V s/rad]"),
        d("SSC_KI", f(ssc.ki), "[V/(rad s)]"),
        d("SSC_KR", f(ssc.kr), "reference weight"),
        d("SSC_TT", f(ssc.tt), "tracking time [s]"),
        "",
        "#endif /* CONTROLLER_PARAMS_H */",
        "",
    ]
    return "\n".join(lines)
