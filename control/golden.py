# Servo scenario: (sample, command, args). Setpoints marked "rel" are relative
# to the angle at that moment and stored as absolute values in the file.
SERVO_SCRIPT = [
    (0, "mode", Mode.SPEED), (1, "sp", 15.0),
    (150, "pid", (Loop.SPEED, 1.3, 1.2)),        # bumpless gain change: scale kp, ki
    (250, "sp", -10.0),                          # reversal: saturates, anti-windup
    (450, "mode", Mode.POSITION),                # catch and hold the current angle
    (550, "sp_rel", 3.0),                        # rate-limited move
    (850, "mode", Mode.STATE),                   # bumpless hand-over to the state controller
    (900, "sp_rel", -2.0),
    (1000, "slew", (Loop.POSITION, 40.0)),
    (1250, "mode", Mode.VOLTAGE), (1251, "sp", 4.0),
    (1400, "mode", Mode.OFF),
]
SERVO_LOAD = (700, 1150, 0.15)   # load torque [N m] between these samples


def servo_golden(cfg: ServoConfig, true: MotorParams, drive: DriveParams, n: int = 1500) -> str:
    """Full servo (all modes, bumpless transfers) in closed loop with the true
    plant; the C test replays the encoder counts and commands.

    Commands: 1 mode(a0), 2 setpoint(a0), 3 pid gains(loop=a0, kp=a1, ki=a2, kd=a3),
    4 slew(loop=a0, rate=a1).
    """
    cfg = f32(cfg)
    servo = Servo(cfg, 0)
    a, b, _, _ = true.state_space()
    phi, gam = c2d_zoh(a, b, drive.ts)
    q = drive.rad_per_count
    x = np.zeros(3)
    script = {k: (c, arg) for k, c, arg in SERVO_SCRIPT}
    rows = []
    for k in range(n):
        counts = math.floor(x[0] / q)
        cmd, args = 0, (0.0, 0.0, 0.0, 0.0)
        if k in script:
            name, arg = script[k]
            if name == "mode":
                cmd, args = 1, (float(arg), 0.0, 0.0, 0.0)
                servo.set_mode(Mode(arg))
            elif name in ("sp", "sp_rel"):
                v = f32(arg + (servo.theta if name == "sp_rel" else 0.0))
                cmd, args = 2, (v, 0.0, 0.0, 0.0)
                servo.set_setpoint(v)
            elif name == "pid":
                loop, fp, fi = arg
                pc = cfg.speed if loop == Loop.SPEED else cfg.pos
                gains = f32((pc.kp * fp, pc.ki * fi, pc.kd))
                cmd, args = 3, (float(loop), *gains)
                servo.set_pid_gains(loop, *gains)
            elif name == "slew":
                loop, rate = arg
                cmd, args = 4, (float(loop), f32(rate), 0.0, 0.0)
                servo.set_slew(loop, args[1])
        u = servo.update(counts)
        rows.append((k, cmd, *args, counts, u, servo.r_eff, servo.omega))
        tau = SERVO_LOAD[2] if SERVO_LOAD[0] <= k < SERVO_LOAD[1] else 0.0
        u_app = min(max(u, -drive.v_supply), drive.v_supply)
        x = phi @ x + gam @ np.array([u_app, tau])
    lines = [
        "# Servo module in closed loop with the true plant: all modes, bumpless transfers,",
        "# gain change, slew change. Configuration = firmware/include/controller_params.h.",
        "# Generated by scripts/run_pipeline.py (control/golden.py) - do not edit.",
        "k,cmd,a0,a1,a2,a3,counts,u,r,omega",
    ]
    for k, cmd, a0, a1, a2, a3, counts, u, r, om in rows:
        lines.append(",".join([str(k), str(cmd), _g(a0), _g(a1), _g(a2), _g(a3), str(counts),
                               _g(u), _g(r), _g(om)]))
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------
def generate(out: PipelineOutput) -> dict[str, str]:
    """All golden files, keyed by file name."""
    true, drive = MotorParams(), DriveParams()
    cfg = out.designs.servo
    sp, pos = cfg.speed, cfg.pos
    pid_full = replace(pos, ki=10.0 * pos.kp, b=0.7, c=0.0, tt=0.05)
    return {
        "pid_speed_pi.csv": pid_golden(
            sp, "Speed PI with back-calculation anti-windup, saturating steps, gain change",
            setpoints=[(20, 10.0), (200, 40.0), (450, -30.0), (700, 5.0)], n=900,
            plant_gain=3.0, plant_tau=0.05, integrating=False,
            gain_change=(600, 1.5 * sp.kp, 0.8 * sp.ki, 0.0), bumpless=None, seed=11),
        "pid_position_pid.csv": pid_golden(
            pid_full, "PID with setpoint weights b = 0.7, c = 0 (D on measurement), filtered D",
            setpoints=[(20, 0.5), (250, -0.8), (500, 0.2)], n=800,
            plant_gain=3.0, plant_tau=0.05, integrating=True,
            gain_change=(350, 0.8 * pid_full.kp, 1.2 * pid_full.ki, 1.1 * pid_full.kd),
            bumpless=(600, 3.0), seed=12),
        "ssc.csv": ssc_golden(cfg.ssc, true, drive),
        "servo.csv": servo_golden(cfg, true, drive),
    }
