"""Golden vectors for the C unit tests (tests/golden/*.csv).

Each file holds an input sequence and the output of the float64 Python
reference implementation. The C library (float32) replays the inputs and must
reproduce the outputs within a tolerance.

To make the comparison about arithmetic only, every parameter and every
input is rounded to float32 *before* the reference runs, and printed with
nine significant digits, which round-trips float32 exactly. Every update in
the library is a continuous function of its inputs (saturation is a clamp,
anti-windup is back-calculation), so float32 rounding can only cause small,
bounded output differences, never a different branch.

File format: '#' lines are comments, '#@ name value' lines are parameters,
then one CSV header line and the data rows.
"""

from __future__ import annotations

import math
from dataclasses import fields, is_dataclass, replace

import numpy as np

from .discrete import PID, PIDConfig, SSCConfig, StateController
from .lti import c2d_zoh
from .motor import DriveParams, MotorParams
from .pipeline import PipelineOutput
from .servo import Loop, Mode, Servo, ServoConfig


def f32(x):
    """Round floats, arrays and (nested) dataclasses to float32 precision."""
    if is_dataclass(x):
        return replace(x, **{f.name: f32(getattr(x, f.name)) for f in fields(x)})
    if isinstance(x, tuple):
        return tuple(f32(v) for v in x)
    if isinstance(x, np.ndarray):
        return x.astype(np.float32).astype(np.float64)
    if isinstance(x, float) and math.isfinite(x):
        return float(np.float32(x))
    return x


def _g(v: float) -> str:
    return f"{v:.9g}"


def _header(title: str, params: dict[str, float]) -> list[str]:
    lines = [f"# {title}",
             "# Generated by scripts/run_pipeline.py (control/golden.py) - do not edit.",
             "# Expected outputs come from the float64 Python reference implementation."]
    lines += [f"#@ {k} {_g(v)}" for k, v in params.items()]
    return lines


def _pid_params(c: PIDConfig) -> dict[str, float]:
    return {"kp": c.kp, "ki": c.ki, "kd": c.kd, "tf": c.tf, "b": c.b, "c": c.c, "ts": c.ts,
            "u_min": c.u_min, "u_max": c.u_max, "tt": c.tt}


# ------------------------------------------------------------------------------
def pid_golden(cfg: PIDConfig, title: str, setpoints: list[tuple[int, float]], n: int,
               plant_gain: float, plant_tau: float, integrating: bool,
               gain_change: tuple[int, float, float, float] | None,
               bumpless: tuple[int, float] | None, seed: int) -> str:
    """PID in closed loop with a crude first-order (optionally integrating)
    plant plus measurement noise. Only the recorded (r, y) pairs matter to the
    C test; the plant just makes the signals and saturation episodes realistic.

    Events (applied before the update of that sample, like in the firmware):
    1 = set_gains(kp=a0, ki=a1, kd=a2) with the row's r and y,
    2 = bumpless_start(r, y, u_now=a0).
    """
    cfg = f32(cfg)
    pid = PID(cfg)
    rng = np.random.default_rng(seed)
    x = xdot = 0.0
    r = 0.0
    sp = dict(setpoints)
    rows = []
    for k in range(n):
        r = f32(sp.get(k, r))
        y = f32(x + 0.01 * plant_gain * rng.standard_normal())
        event, a = 0, (0.0, 0.0, 0.0)
        if gain_change and k == gain_change[0]:
            event, a = 1, f32(tuple(gain_change[1:]))
            pid.set_gains(*a, r, y)
        if bumpless and k == bumpless[0]:
            event, a = 2, (f32(bumpless[1]), 0.0, 0.0)
            pid.bumpless_start(r, y, a[0])
        u = pid.update(r, y)
        rows.append((k, event, *a, r, y, u))
        # first-order lag (speed-like) or lag + integrator (position-like), explicit Euler
        xdot += cfg.ts / plant_tau * (plant_gain * u - xdot)
        x = x + cfg.ts * xdot if integrating else xdot
    lines = _header(title, _pid_params(cfg))
    lines.append("k,event,a0,a1,a2,r,y,u")
    lines += [",".join([str(k), str(ev)] + [_g(v) for v in rest]) for k, ev, *rest in rows]
    return "\n".join(lines) + "\n"


def ssc_golden(cfg: SSCConfig, true: MotorParams, drive: DriveParams, n: int = 900) -> str:
    """State controller on the true plant (quantised angle), setpoint steps large
    enough to saturate the output, and a bumpless restart at k = 600.

    Events: 2 = bumpless_start(r, theta0=a0, omega0=a1, u_now=a2).
    """
    cfg = f32(cfg)
    ctrl = StateController(cfg)
    a, b, _, _ = true.state_space()
    phi, gam = c2d_zoh(a, b[:, [0]], drive.ts)
    q = drive.rad_per_count
    x = np.zeros(3)
    setpoints = {20: 0.5, 250: -1.5, 450: -1.2}
    r = 0.0
    rows = []
    u = 0.0
    for k in range(n):
        r = f32(setpoints.get(k, r))
        y = f32(math.floor(x[0] / q) * q)
        event, args = 0, (0.0, 0.0, 0.0)
        if k == 600:
            event, args = 2, f32((y, float(x[1]), u))
            ctrl.bumpless_start(r, *args)
        u = ctrl.update(r, y)
        rows.append((k, event, *args, r, y, u))
        x = phi @ x + gam[:, 0] * u
    params = {"phi00": cfg.phi[0, 0], "phi01": cfg.phi[0, 1], "phi10": cfg.phi[1, 0],
              "phi11": cfg.phi[1, 1], "gamma0": cfg.gamma[0], "gamma1": cfg.gamma[1],
              "l0": cfg.l[0], "l1": cfg.l[1], "k0": cfg.k[0], "k1": cfg.k[1], "ki": cfg.ki,
              "kr": cfg.kr, "ts": cfg.ts, "u_min": cfg.u_min, "u_max": cfg.u_max, "tt": cfg.tt}
    lines = _header("State feedback + observer on the true plant, saturating steps", params)
    lines.append("k,event,a0,a1,a2,r,y,u")
    lines += [",".join([str(k), str(ev)] + [_g(v) for v in rest]) for k, ev, *rest in rows]
    return "\n".join(lines) + "\n"


